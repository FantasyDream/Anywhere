import importlib.util
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

spec = importlib.util.spec_from_file_location(
    'code_style',
    Path(__file__).resolve().parents[1] / 'check-code-style.py')
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


class CodeStyleSourcesTests(unittest.TestCase):

    def discover(self, files):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            for name, content in files.items():
                if content is not None:
                    path = root / name
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(content)
            listing = b'\0'.join(name.encode() for name in files) + b'\0'
            with patch.object(module, 'ROOT',
                              root), patch.object(module.subprocess,
                                                  'check_output',
                                                  return_value=listing):
                return module.sources()

    def test_generated_artifacts_and_deleted_sources_are_not_reformatted(self):
        groups = self.discover({
            'apps/flutter/lib/src/rust/bridge.dart':
                'class Bridge {}',
            'apps/flutter/lib/l10n/generated/messages.dart':
                'class Messages {}',
            'packages/sdk/contract.ts':
                '// Generated by schema; do not edit\n',
            'apps/flutter/lib/ui/tokens.dart':
                '// Automatically generated\n',
            'removed.py':
                None,
        })
        self.assertTrue(all(not paths for paths in groups.values()))

    def test_handwritten_dist_and_new_tool_configs_are_checked(self):
        groups = self.discover({
            'plugins/examples/web-text/dist/main.js': 'const text = "hi";\n',
            '.prettierrc.cjs': 'module.exports = {};\n',
            'scripts/new.py': 'print("hi")\n',
        })
        self.assertEqual(
            groups['web'],
            ['.prettierrc.cjs', 'plugins/examples/web-text/dist/main.js'])
        self.assertEqual(groups['python'], ['scripts/new.py'])


if __name__ == '__main__':
    unittest.main()
