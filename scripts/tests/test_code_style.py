import importlib.util
from pathlib import Path
import sys
import tempfile
import unittest
from unittest.mock import patch

SCRIPTS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SCRIPTS))
spec = importlib.util.spec_from_file_location('code_style',
                                              SCRIPTS / 'check-code-style.py')
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


class CodeStyleSourcesTests(unittest.TestCase):

    def discover(self, files):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            for name, content in files.items():
                if content is not None:
                    path = root / name
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(content)
            listing = b'\0'.join(name.encode() for name in files) + b'\0'
            with patch.object(module, 'ROOT',
                              root), patch.object(module.subprocess,
                                                  'check_output',
                                                  return_value=listing):
                return module.sources()

    def test_generated_artifacts_and_deleted_sources_are_not_reformatted(self):
        groups = self.discover({
            'packages/sdk/contract.ts': '// Generated by schema; do not edit\n',
            'packages/sdk/tokens.css': '// Automatically generated\n',
            'removed.py': None,
        })
        self.assertTrue(all(not paths for paths in groups.values()))

    def test_handwritten_dist_and_new_tool_configs_are_checked(self):
        groups = self.discover({
            'plugins/examples/web-text/dist/main.js': 'const text = "hi";\n',
            '.prettierrc.cjs': 'module.exports = {};\n',
            'scripts/new.py': 'print("hi")\n',
        })
        self.assertEqual(
            groups['web'],
            ['.prettierrc.cjs', 'plugins/examples/web-text/dist/main.js'])
        self.assertEqual(groups['python'], ['scripts/new.py'])

    def test_px_literal_budget_allows_reduction_and_rejects_growth(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            file_path = root / 'apps/gpui/src/launcher/view/example.rs'
            file_path.parent.mkdir(parents=True, exist_ok=True)
            budget_path = root / 'scripts/px-literal-budget.json'
            budget_path.parent.mkdir(parents=True, exist_ok=True)
            budget_path.write_text(
                '{"files": {"apps/gpui/src/launcher/view/example.rs": 1}}\n')

            file_path.write_text(
                'fn render() { let _ = px(12.); }\n#[cfg(test)]\nmod tests { fn t() { let _ = px(99.); } }\n'
            )
            self.assertEqual(
                module.check_px_literal_budget(root=root,
                                               budget_path=budget_path),
                [],
            )

            file_path.write_text(
                'fn render() { let _ = px(12.); }\n'
                '#[cfg(test)]\nfn fixture() { let _ = px(99.); }\n'
                'fn render_other() { let _ = px(16.); }\n')
            errors = module.check_px_literal_budget(root=root,
                                                    budget_path=budget_path)
            self.assertEqual(len(errors), 1)
            self.assertIn('exceeds budget 1', errors[0])

            unlisted = root / 'apps/gpui/src/launcher/view/new_file.rs'
            unlisted.write_text('fn render() { let _ = px(8.); }\n')
            errors = module.check_px_literal_budget(root=root,
                                                    budget_path=budget_path)
            self.assertEqual(len(errors), 2)


if __name__ == '__main__':
    unittest.main()
