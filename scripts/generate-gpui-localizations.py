#!/usr/bin/env python3
"""Generate the committed, typed GPUI localization module from the product ARB files."""

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
LOCALES = ('en', 'zh')
OUTPUT = ROOT / 'apps/gpui/src/l10n/generated.rs'
SOURCE_DIRECTORY = ROOT / 'resources/localization'

RUST_KEYWORDS = {
    'as', 'break', 'const', 'continue', 'crate', 'else', 'enum', 'extern',
    'false', 'fn', 'for', 'if', 'impl', 'in', 'let', 'loop', 'match', 'mod',
    'move', 'mut', 'pub', 'ref', 'return', 'self', 'static', 'struct', 'super',
    'trait', 'true', 'type', 'unsafe', 'use', 'where', 'while', 'async',
    'await', 'dyn', 'abstract', 'become', 'box', 'do', 'final', 'macro',
    'override', 'priv', 'typeof', 'unsized', 'virtual', 'yield', 'try'
}


def rust_ident(name):
    """Return an identifier safe for a function name or Rust parameter."""
    if name in RUST_KEYWORDS:
        return 'r#' + name
    return name


def snake(name):
    return rust_ident(re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name).lower())


def matching_brace(value, start):
    depth = 0
    for index in range(start, len(value)):
        if value[index] == '{':
            depth += 1
        elif value[index] == '}':
            depth -= 1
            if depth == 0:
                return index
    raise ValueError('Unbalanced plural braces')


def parse_plural(message):
    match = re.search(r'\{([A-Za-z_][A-Za-z0-9_]*)\s*,\s*plural\s*,\s*',
                      message)
    if match is None:
        return None
    key = match.group(1)
    options = {}
    cursor = match.end()
    while cursor < len(message):
        while cursor < len(message) and message[cursor].isspace():
            cursor += 1
        selector = re.match(r'(=[-0-9]+|[A-Za-z]+)\s*\{', message[cursor:])
        if selector is None:
            raise ValueError(f'Invalid plural option in {message!r}')
        choice = selector.group(1)
        body_start = cursor + selector.end() - 1
        body_end = matching_brace(message, body_start)
        options[choice] = message[body_start + 1:body_end]
        cursor = body_end + 1
        while cursor < len(message) and message[cursor].isspace():
            cursor += 1
        if cursor < len(message) and message[cursor] == '}':
            cursor += 1
            break
    if 'other' not in options:
        raise ValueError(f'Plural has no other branch: {message!r}')
    return key, options, message[:match.start()], message[cursor:]


def rust_string(value):
    return json.dumps(value, ensure_ascii=False)


def reject_duplicate_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f'Duplicate localization key: {key}')
        result[key] = value
    return result


def read_catalog(path):
    return json.loads(path.read_text(), object_pairs_hook=reject_duplicate_keys)


def message_count():
    catalog = read_catalog(SOURCE_DIRECTORY / 'app_en.arb')
    return len([key for key in catalog if not key.startswith('@')])


def render():
    catalogs = {
        locale: read_catalog(SOURCE_DIRECTORY / f'app_{locale}.arb')
        for locale in LOCALES
    }
    english_keys = [key for key in catalogs['en'] if not key.startswith('@')]
    for locale in LOCALES:
        keys = [key for key in catalogs[locale] if not key.startswith('@')]
        if keys != english_keys:
            raise ValueError(
                f'{locale} message order or keys differ from English')

    names = [snake(key) for key in english_keys]
    if len(names) != len(set(names)):
        raise ValueError('ARB keys collide after snake-case conversion')

    output = [
        '// Generated by scripts/generate-gpui-localizations.py. Do not edit.',
        '',
        '#[derive(Clone, Copy, Debug, Eq, PartialEq)]',
        'pub enum Locale { En, Zh }',
        '',
        'fn plural_category(count: i64) -> &\'static str {',
        '    if count == 1 { "one" } else { "other" }',
        '}',
        '',
        'fn fill(template: &str, values: &[(&str, String)]) -> String {',
        '    let mut result = template.to_owned();',
        '    for (name, value) in values {',
        '        result = result.replace(&format!("{{{name}}}"), value);',
        '    }',
        '    result',
        '}',
        '',
        'fn plural(template: &str, _count: i64, values: &[(&str, String)]) -> String {',
        '    fill(template, values)',
        '}',
        '',
    ]

    for key in english_keys:
        rust_name = snake(key)
        placeholders = catalogs['en'].get('@' + key, {}).get('placeholders', {})
        params = []
        values = []
        for name, metadata in placeholders.items():
            kind = metadata.get('type', 'String')
            if kind not in ('String', 'int'):
                raise ValueError(
                    f'Unsupported placeholder type {kind}: {key}/{name}')
            params.append(
                f'{rust_ident(name)}: {"i64" if kind == "int" else "&str"}')
            values.append(f'("{name}", {rust_ident(name)}.to_string())')
        plural_data = [
            parse_plural(catalogs[locale][key]) for locale in LOCALES
        ]
        is_plural = any(value is not None for value in plural_data)

        if is_plural:
            count_names = {
                value[0] for value in plural_data if value is not None
            }
            if len(count_names) != 1:
                raise ValueError(f'Plural count key differs: {key}')
            count_name = next(iter(count_names))
            if count_name not in placeholders or placeholders[count_name].get(
                    'type') != 'int':
                raise ValueError(
                    f'Plural count is not an int placeholder: {key}')
        else:
            count_name = None

        signature = ', '.join(['locale: Locale'] + params)
        output.append(f'pub fn {rust_name}({signature}) -> String {{')
        if not placeholders and not is_plural:
            output.append('    match locale {')
            for locale in LOCALES:
                output.append(
                    f'        Locale::{locale.title()} => {rust_string(catalogs[locale][key])}.to_string(),'
                )
            output.append('    }')
        else:
            argument_pairs = ', '.join(values)
            output.append('    let values = &[' + argument_pairs + '];')
            output.append('    match locale {')
            for locale in LOCALES:
                data = plural_data[LOCALES.index(locale)]
                if data is None:
                    output.append(
                        f'        Locale::{locale.title()} => fill({rust_string(catalogs[locale][key])}, values),'
                    )
                else:
                    parsed_count, options, prefix, suffix = data
                    exact = ', '.join(
                        f'Some({selector[1:]}) => {rust_string(prefix + body + suffix)}'
                        for selector, body in options.items()
                        if selector.startswith('='))
                    output.append(f'        Locale::{locale.title()} => {{')
                    output.append(
                        f'            let template = match Some({parsed_count}) {{'
                    )
                    if exact:
                        output.append('                ' + exact + ',')
                    output.append(
                        '                _ => match plural_category(' +
                        parsed_count + ') {')
                    for selector, body in options.items():
                        if selector.startswith('='):
                            continue
                        output.append(
                            f'                    {rust_string(selector)} => {rust_string(body)},'
                        )
                    output.append(
                        f'                    _ => {rust_string(prefix + options["other"] + suffix)},'
                    )
                    output.append('                },')
                    output.append('            };')
                    output.append(
                        f'            plural(template, {parsed_count}, values)')
                    output.append('        }')
            output.append('    }')
        output.append('}')
        output.append('')

    output += [
        '/// Stable message count for generated-resource verification.',
        f'pub const MESSAGE_COUNT: usize = {len(english_keys)};',
        '',
    ]
    unformatted = '\n'.join(output)
    return subprocess.run(
        ['rustfmt', '--emit', 'stdout', '--edition', '2021'],
        input=unformatted,
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    value = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != value:
            print(f'Outdated GPUI localizations: {OUTPUT.relative_to(ROOT)}',
                  file=sys.stderr)
            return 1
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(value)
    print(f'GPUI localizations OK: {message_count()} messages, '
          'en/zh, placeholders and plurals')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
