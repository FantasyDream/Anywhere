#!/usr/bin/env python3
"""Check or apply the repository's language-specific Google style tools."""
import argparse
from pathlib import Path
import platform
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
PYTOOLS = ROOT / '.tools/code-style/python/bin'
NODETOOLS = ROOT / 'tools/code-style/node_modules'
SWIFT_FORMAT = ROOT / '.tools/code-style/swift-format/.build/release/swift-format'


def sources():
    result = subprocess.check_output(
        ['git', 'ls-files', '--cached', '--others', '--exclude-standard', '-z'],
        cwd=ROOT)
    groups = {
        name: [] for name in
        ['dart', 'web', 'jsx', 'python', 'native', 'swift', 'shell']
    }
    suffixes = {
        '.dart': 'dart',
        '.ts': 'web',
        '.js': 'web',
        '.mjs': 'web',
        '.cjs': 'web',
        '.jsx': 'jsx',
        '.py': 'python',
        '.m': 'native',
        '.h': 'native',
        '.c': 'native',
        '.cc': 'native',
        '.cpp': 'native',
        '.swift': 'swift',
        '.sh': 'shell'
    }
    for raw in sorted(set(result.split(b'\0'))):
        if not raw:
            continue
        name = raw.decode('utf-8')
        path = ROOT / name
        group = suffixes.get(path.suffix)
        if group is None or not path.is_file():
            continue
        if name.startswith(
            ('apps/flutter/lib/src/rust/', 'apps/flutter/lib/l10n/generated/')):
            continue
        header = '\n'.join(path.read_text().splitlines()[:5])
        if re.search(
                r'generated by|generated.*do not edit|automatically generated|generated code',
                header, re.IGNORECASE):
            continue
        groups[group].append(name)
    return groups


def run(command):
    subprocess.run([str(value) for value in command], cwd=ROOT, check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fix',
                        action='store_true',
                        help='Apply formatting and safe lint fixes')
    parser.add_argument(
        '--language',
        choices=['dart', 'web', 'python', 'native', 'swift', 'shell', 'rust'])
    args = parser.parse_args()
    groups = sources()
    wanted = {args.language} if args.language else set(groups)
    if args.language == 'web':
        wanted.add('jsx')
    for language, files in groups.items():
        if language not in wanted or not files:
            continue
        print(f'Code style: {language} ({len(files)} files)', flush=True)
        if language == 'dart':
            run([
                'dart', 'format', *([] if args.fix else
                                    ['--output=none', '--set-exit-if-changed']),
                *files
            ])
        elif language == 'web':
            run([
                'node', NODETOOLS / 'eslint/bin/eslint.js', '--config',
                'tools/code-style/eslint.config.mjs', '--max-warnings=0',
                *(['--fix'] if args.fix else []), *files
            ])
        elif language == 'jsx':
            run([
                'node', NODETOOLS / 'prettier/bin/prettier.cjs',
                '--write' if args.fix else '--check', *files
            ])
        elif language == 'python':
            run([
                PYTOOLS / 'yapf', '--style', '.style.yapf',
                '--in-place' if args.fix else '--diff', *files
            ])
        elif language == 'native':
            run([
                PYTOOLS / 'clang-format',
                *(['-i'] if args.fix else ['--dry-run', '--Werror']), *files
            ])
        elif language == 'swift':
            if platform.system() != 'Darwin':
                print('Swift formatting is checked by the macOS gate.',
                      flush=True)
                continue
            run([
                SWIFT_FORMAT, 'format' if args.fix else 'lint',
                '--configuration', '.swift-format',
                *(['--in-place'] if args.fix else ['--strict']), *files
            ])
        elif language == 'shell':
            run([
                PYTOOLS / 'shfmt', '-i', '2', '-ci', '-w' if args.fix else '-d',
                *files
            ])
            run([PYTOOLS / 'shellcheck', '--external-sources', *files])
    if args.language in (None, 'rust'):
        run(['cargo', 'fmt', '--all', *([] if args.fix else ['--check'])])


if __name__ == '__main__':
    try:
        main()
    except FileNotFoundError:
        sys.exit(
            'Missing code style tool. Run scripts/setup-code-style.sh first.')
    except subprocess.CalledProcessError as error:
        sys.exit(error.returncode)
