#!/usr/bin/env python3
"""Project the shared ARB catalog into Apple's native .strings files and typed keys."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def generate(check=False):
    keys = json.loads(
        (ROOT / 'resources/native-localization-keys.json').read_text())
    if len(keys) != len(set(keys)):
        raise SystemExit('Duplicate native localization key')
    catalogs = {
        locale:
            json.loads(
                (ROOT / f'apps/flutter/lib/l10n/app_{locale}.arb').read_text())
        for locale in ('en', 'zh')
    }
    outputs = {}
    swift = [
        '// Generated by scripts/generate-native-localizations.py; edit ARB resources.',
        'enum NativeText: String {'
    ]
    swift += [f'    case {key}' for key in keys]
    swift += ['    var english: String {', '        switch self {']
    for key in keys:
        value = catalogs['en'][key]
        if '{' in value:
            raise SystemExit(
                f'Native fixed label cannot contain placeholders: {key}')
        swift.append(
            f'        case .{key}: return {json.dumps(value, ensure_ascii=False)}'
        )
    swift += ['        }', '    }', '}', '']
    outputs[ROOT /
            'apps/flutter/macos/Runner/NativeText.g.swift'] = '\n'.join(swift)
    for locale, apple in [('en', 'en'), ('zh', 'zh-Hans')]:
        lines = ['/* Generated from the shared ARB catalog. */']
        for key in keys:
            lines.append(
                f'{json.dumps(key)} = {json.dumps(catalogs[locale][key], ensure_ascii=False)};'
            )
        outputs[
            ROOT /
            f'resources/native-localizations/{apple}.lproj/Anywhere.strings'] = '\n'.join(
                lines) + '\n'
        outputs[
            ROOT /
            f'resources/native-localizations/{apple}.lproj/InfoPlist.strings'] = (
                '/* Generated from the shared ARB catalog. */\n' +
                '"NSAppleEventsUsageDescription" = ' +
                json.dumps(catalogs[locale]['automationUsage'],
                           ensure_ascii=False) + ';\n')
    for path, value in outputs.items():
        if check:
            if not path.exists() or path.read_text() != value:
                raise SystemExit(
                    f'Stale native localizations: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    print(f'Native localizations OK: {len(keys)} keys, en/zh, Apple .strings')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
