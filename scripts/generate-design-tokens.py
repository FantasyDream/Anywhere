#!/usr/bin/env python3
"""Generate presentation-only GPUI and Web tokens from one source. Colors are ARGB."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent


def css_name(name):
    return '--aw-' + re.sub(r'([A-Z])', r'-\1', name).lower()


def rust_name(name):
    return re.sub(r'([A-Z])', r'_\1', name).upper()


def rust_field(name):
    return re.sub(r'([A-Z])', r'_\1', name).lower()


def rust_font_family(stack):
    """Project the first CSS family to a GPUI family name."""
    first = stack.split(',', 1)[0].strip().strip('"\'')
    if first in {'-apple-system', 'BlinkMacSystemFont', 'system-ui'}:
        return '.SystemUIFont'
    return first


def css_color(argb):
    if not isinstance(argb, str) or not re.fullmatch(r'#[0-9a-fA-F]{8}', argb):
        raise ValueError('Expected #AARRGGBB color')
    return '#' + argb[3:].lower() + argb[1:3].lower()


def expand_palettes(raw_palettes):
    required = ('opaqueDark', 'glassDark', 'glassLight')
    if set(raw_palettes) != set(required):
        raise ValueError('Palettes must be opaqueDark, glassDark, glassLight')
    expanded = {}
    for name in required:
        entry = raw_palettes[name]
        if 'extends' in entry:
            base_name = entry['extends']
            if base_name == name or base_name not in raw_palettes:
                raise ValueError(f'Invalid palette extends target: {base_name}')
            if 'extends' in raw_palettes[base_name]:
                raise ValueError(
                    f'Nested palette extends not allowed: {name} -> {base_name}'
                )
            merged = {
                k: v
                for k, v in raw_palettes[base_name].items()
                if k != 'extends'
            }
            merged.update({k: v for k, v in entry.items() if k != 'extends'})
            expanded[name] = merged
        else:
            expanded[name] = dict(entry)
    expected_roles = set(expanded['opaqueDark'])
    if not expected_roles:
        raise ValueError('Palette roles cannot be empty')
    for name, palette in expanded.items():
        if set(palette) != expected_roles:
            raise ValueError(f'Palette {name} roles differ from opaqueDark')
        for key, value in palette.items():
            if key.startswith(('glassLight', 'glassDark')):
                raise ValueError(f'Legacy prefix key forbidden: {key}')
            css_color(value)
    return expanded


def expand_contrast(expanded_palettes, fixed, contrast):
    if set(contrast) != {'opaqueDark', 'glassDark', 'glassLight', 'fixed'}:
        raise ValueError('Contrast keys must cover all palettes and fixed')
    result = {}
    for name, base in expanded_palettes.items():
        overlay = contrast[name]
        if not set(overlay).issubset(set(base)):
            raise ValueError(f'Unknown contrast role in {name}')
        for value in overlay.values():
            css_color(value)
        result[name] = {**base, **overlay}
    fixed_overlay = contrast['fixed']
    if not set(fixed_overlay).issubset(set(fixed)):
        raise ValueError('Unknown contrast role in fixed')
    for value in fixed_overlay.values():
        css_color(value)
    result['fixed'] = {**fixed, **fixed_overlay}
    return result


def render(spec):
    if spec.get('schemaVersion') != 3 or spec.get('colorFormat') != 'ARGB':
        raise ValueError('Unsupported design token schema')
    palettes = expand_palettes(spec['palettes'])
    fixed = spec['fixed']
    for value in fixed.values():
        css_color(value)
    palette_roles = list(palettes['opaqueDark'])
    fixed_roles = list(fixed)
    if set(palette_roles) & set(fixed_roles):
        raise ValueError('Fixed color names cannot overlap palette roles')
    contrast_sets = expand_contrast(palettes, fixed, spec['contrast'])

    names = [
        *palette_roles,
        *fixed_roles,
        *(key for group in ['metrics', 'fonts'] for key in spec[group]),
    ]
    if len(names) != len(set(names)) or any(
            not re.fullmatch(r'[a-z][A-Za-z0-9]*', k) for k in names):
        raise ValueError('Invalid or duplicate token name')

    css = []
    for key in palette_roles:
        css.append(
            f'  {css_name(key)}: {css_color(palettes["opaqueDark"][key])};')
    for key in fixed_roles:
        css.append(f'  {css_name(key)}: {css_color(fixed[key])};')

    rust = [
        '// Generated by scripts/generate-design-tokens.py. Do not edit.',
        '#![allow(clippy::unreadable_literal)]',
        '',
        '#[derive(Clone, Copy, Debug, Eq, PartialEq)]',
        'pub struct Palette {',
    ]
    for key in palette_roles:
        rust.append(f'    pub {rust_field(key)}: u32,')
    rust += [
        '}',
        '',
        'impl Palette {',
        f'    pub fn web_variables(&self) -> [(&\'static str, u32); {len(palette_roles)}] {{',
        '        [',
    ]
    for key in palette_roles:
        rust.append(
            f'            ({json.dumps(css_name(key))}, self.{rust_field(key)}),'
        )
    rust += [
        '        ]',
        '    }',
        '}',
        '',
        'pub mod colors {',
        '    use super::Palette;',
        '',
        '    #[derive(Clone, Copy, Debug, Eq, PartialEq)]',
        '    pub struct FixedColors {',
    ]
    for key in fixed_roles:
        rust.append(f'        pub {rust_field(key)}: u32,')
    contrast_fixed_roles = list(spec['contrast']['fixed'])
    rust += [
        '    }',
        '',
        '    impl FixedColors {',
        f'        pub fn web_contrast_variables(&self) -> [(&\'static str, u32); {len(contrast_fixed_roles)}] {{',
        '            [',
    ]
    for key in contrast_fixed_roles:
        name = json.dumps(css_name(key))
        field = f'self.{rust_field(key)}'
        assignment = f'                ({name}, {field}),'
        if len(assignment) <= 80:
            rust.append(assignment)
        else:
            rust += [
                '                (',
                f'                    {name},',
                f'                    {field},',
                '                ),',
            ]
    rust += ['            ]', '        }', '    }', '']

    def append_struct_const(const_name,
                            struct_name,
                            fields,
                            mapping,
                            indent='    '):
        rust.append(
            f'{indent}pub const {const_name}: {struct_name} = {struct_name} {{')
        for key in fields:
            rust.append(
                f'{indent}    {rust_field(key)}: 0x{mapping[key][1:].lower()},')
        rust.append(f'{indent}}};')

    for key_name, const_name in [
        ('opaqueDark', 'OPAQUE_DARK'),
        ('glassDark', 'GLASS_DARK'),
        ('glassLight', 'GLASS_LIGHT'),
    ]:
        append_struct_const(const_name, 'Palette', palette_roles,
                            palettes[key_name])
        append_struct_const(f'{const_name}_CONTRAST', 'Palette', palette_roles,
                            contrast_sets[key_name])
    append_struct_const('FIXED', 'FixedColors', fixed_roles, fixed)
    append_struct_const('FIXED_CONTRAST', 'FixedColors', fixed_roles,
                        contrast_sets['fixed'])

    rust += ['}', '', 'pub mod metrics {']
    for key, item in spec['metrics'].items():
        value, unit = item['value'], item['unit']
        if isinstance(value, bool) or not isinstance(
                value, (int, float)) or not 0 <= value <= 1000 or unit not in [
                    'px', 'number', 'fontWeight'
                ]:
            raise ValueError('Invalid numeric design token')
        if unit == 'fontWeight':
            if value not in range(100, 1000, 100):
                raise ValueError('Invalid font weight')
        css.append(
            f'  {css_name(key)}: {value:g}{"px" if unit == "px" else ""};')
        rust.append(f'    pub const {rust_name(key)}: f32 = {float(value):.6};')
    rust += ['}', '', 'pub mod fonts {']
    windows_fonts = spec.get('windowsFonts', {})
    if not set(windows_fonts).issubset(spec['fonts']):
        raise ValueError('Unknown Windows font token')
    for key, value in spec['fonts'].items():
        if not isinstance(value, str) or any(c in value for c in ';{}<>\n\r'):
            raise ValueError('Invalid font stack')
        css.append(f'  {css_name(key)}: {value};')
        if key in windows_fonts:
            family = windows_fonts[key]
            if not isinstance(family, str) or not re.fullmatch(
                    r'[A-Za-z0-9 ]+', family):
                raise ValueError('Invalid Windows font family')
            rust += [
                '    #[cfg(windows)]',
                f'    pub const {rust_name(key)}: &str = {json.dumps(family)};',
                '    #[cfg(not(windows))]',
            ]
        rust.append(
            f'    pub const {rust_name(key)}: &str = {json.dumps(rust_font_family(value))};'
        )
    rust += ['}', '']
    for key, target in spec['aliases'].items():
        if not re.fullmatch(r'[a-z][A-Za-z0-9]*', key) or key in names or (
                target not in palette_roles and target not in fixed_roles):
            raise ValueError('Invalid alias')
        css.append(f'  {css_name(key)}: var({css_name(target)});')
        source = ('colors::OPAQUE_DARK'
                  if target in palette_roles else 'colors::FIXED')
        rust.append(
            f'pub const {rust_name(key)}: u32 = {source}.{rust_field(target)};')
    css = (
        '/* Generated by scripts/generate-design-tokens.py. Do not edit. */\n'
        ':root {\n' + '\n'.join(css) + '\n}\n'
        ':root { color-scheme: dark; }\n'
        'html, body { background: var(--aw-web-canvas, var(--aw-fallback-surface)); color: var(--aw-text); '
        'font-family: var(--aw-font-ui); font-size: var(--aw-body-size); '
        'line-height: var(--aw-body-line-height); }\n')
    return css, '\n'.join(rust) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    css, rust = render(
        json.loads((ROOT / 'resources/design-tokens.json').read_text()))
    controls = (ROOT / 'resources/web-controls.css').read_text()
    for path, content in [
        (ROOT / 'packages/plugin-sdk/styles/tokens.css', css),
        (ROOT / 'packages/plugin-sdk/styles/controls.css',
         '/* Generated by scripts/generate-design-tokens.py. Do not edit. */\n'
         + controls),
        (ROOT / 'apps/gpui/src/ui/design_tokens.rs', rust),
    ]:
        if args.check:
            if not path.exists() or path.read_text() != content:
                print(
                    f'Outdated generated design tokens: {path.relative_to(ROOT)}',
                    file=sys.stderr)
                return 1
        else:
            path.write_text(content)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
