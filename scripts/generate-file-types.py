#!/usr/bin/env python3
"""Generate the Rust filename filtering contract from one resource."""
import argparse
import json
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
spec = json.loads((root / 'resources/file-types.json').read_text())
header = '// Generated by scripts/generate-file-types.py; edit resources/file-types.json.\n'
rust = header + '''use anywhere_protocol::FileSearchFilter;
pub fn accepts(filter: FileSearchFilter, name: &str, directory: bool) -> bool {
use FileSearchFilter::*;
match filter { All => return true, Files => return !directory, Folders => return directory, _ => {} }
if directory { return false; }
let name = name.to_lowercase();
let extension = name.rsplit_once('.').map(|(_, ext)| ext).unwrap_or("");
let extensions: &[&str] = match filter {
'''
for item in spec[3:]:
    rust += f"{item['rust']} => &[" + ','.join(
        json.dumps(e) for e in item['extensions']) + '],\n'
rust += '_ => &[],\n};\nextensions.contains(&extension) || (filter == Code && (name.starts_with(".env.") || [' + ','.join(
    json.dumps(n)
    for n in spec[-1]['names']) + '].contains(&name.as_str())))\n}\n'
protocol = header + 'use serde::{Deserialize, Serialize};\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]\npub enum FileSearchFilter {\n'
for i, item in enumerate(spec):
    if i == 0:
        protocol += '#[default]\n'
    protocol += item['rust'] + ',\n'
protocol += '}\n'
icons = spec[0]['icons']
icon_rust = header + '#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum FileIconKind {\n' + ','.join(
    item['kind'] for item in icons) + '}\n'
icon_rust += "pub fn kind(name: &str) -> Option<FileIconKind> { let name = name.rsplit(['/', '\\\\']).next().unwrap_or(name).to_ascii_lowercase();\n"
for item in icons:
    conditions = [
        'name == ' + json.dumps(name) for name in item.get('names', [])
    ]
    conditions += [
        'name.starts_with(' + json.dumps(prefix) + ')'
        for prefix in item.get('prefixes', [])
    ]
    if conditions:
        icon_rust += 'if ' + ' || '.join(
            conditions
        ) + ' { return Some(FileIconKind::' + item['kind'] + '); }\n'
icon_rust += "let extension = name.rsplit_once('.').filter(|(stem, ext)| !stem.is_empty() && !ext.is_empty()).map(|(_, ext)| ext)?;\nmatch extension {\n"
claimed = set()
for item in icons:
    extensions = list(item.get('extensions', []))
    if 'filter' in item:
        extensions += next(entry['extensions']
                           for entry in spec
                           if entry['id'] == item['filter'])
    extensions = [
        value for value in dict.fromkeys(extensions)
        if value not in item.get('exclude', []) and value not in claimed
    ]
    claimed.update(extensions)
    if extensions:
        icon_rust += '|'.join(
            json.dumps(value) for value in extensions
        ) + ' => Some(FileIconKind::' + item['kind'] + '),\n'
icon_rust += '_ => None, } }\n'
with tempfile.TemporaryDirectory() as scratch:
    outputs = [('apps/gpui/src/launcher/file_icons.rs', icon_rust,
                ['rustfmt', '--edition', '2021']),
               ('crates/anywhere-protocol/src/file_filter.rs', protocol,
                ['rustfmt', '--edition', '2021']),
               ('crates/anywhere-core/src/features/filesystem/file_types.rs',
                rust, ['rustfmt', '--edition', '2021'])]
    for target, content, formatter in outputs:
        path = Path(scratch) / Path(target).name
        path.write_text(content)
        subprocess.run(formatter + [str(path)], check=True, capture_output=True)
        destination = root / target
        rendered = path.read_text()
        if args.check:
            assert destination.read_text(
            ) == rendered, f'Outdated generated file: {target}'
        else:
            destination.write_text(rendered)
