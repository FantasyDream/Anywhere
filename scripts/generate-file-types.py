#!/usr/bin/env python3
"""One filename filtering contract; Flutter receives labels, Rust classifies."""
import argparse
import json
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
spec = json.loads((root / 'resources/file-types.json').read_text())
header = '// Generated by scripts/generate-file-types.py; edit resources/file-types.json.\n'
dart = header + 'enum FileFilter {\n'
for item in spec:
    dart += f"  {item['id']}({json.dumps(item['label'])}),\n"
dart = dart.rstrip(
    ',\n') + ';\n  const FileFilter(this.label);\n  final String label;\n}\n'
rust = header + '''use anywhere_protocol::FileSearchFilter;
pub fn accepts(filter: FileSearchFilter, name: &str, directory: bool) -> bool {
use FileSearchFilter::*;
match filter { All => return true, Files => return !directory, Folders => return directory, _ => {} }
if directory { return false; }
let name = name.to_lowercase();
let extension = name.rsplit_once('.').map(|(_, ext)| ext).unwrap_or("");
let extensions: &[&str] = match filter {
'''
for item in spec[3:]:
    rust += f"{item['rust']} => &[" + ','.join(
        json.dumps(e) for e in item['extensions']) + '],\n'
rust += '_ => &[],\n};\nextensions.contains(&extension) || (filter == Code && (name.starts_with(".env.") || [' + ','.join(
    json.dumps(n)
    for n in spec[-1]['names']) + '].contains(&name.as_str())))\n}\n'
protocol = header + 'use serde::{Deserialize, Serialize};\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]\npub enum FileSearchFilter {\n'
for i, item in enumerate(spec):
    if i == 0:
        protocol += '#[default]\n'
    protocol += item['rust'] + ',\n'
protocol += '}\nimpl FileSearchFilter {\npub fn from_wire(name: &str) -> Option<Self> {\nmatch name {\n'
for item in spec:
    protocol += f'{json.dumps(item["id"])} => Some(Self::{item["rust"]}),\n'
protocol += '_ => None,\n}\n}\n}\n'
with tempfile.TemporaryDirectory() as scratch:
    outputs = [('crates/anywhere-protocol/src/file_filter.rs', protocol,
                ['rustfmt', '--edition', '2021']),
               ('apps/flutter/lib/launcher/file_filter.dart', dart,
                ['dart', 'format']),
               ('crates/anywhere-core/src/features/filesystem/file_types.rs',
                rust, ['rustfmt', '--edition', '2021'])]
    for target, content, formatter in outputs:
        path = Path(scratch) / Path(target).name
        path.write_text(content)
        subprocess.run(formatter + [str(path)], check=True, capture_output=True)
        destination = root / target
        rendered = path.read_text()
        if args.check:
            assert destination.read_text(
            ) == rendered, f'Outdated generated file: {target}'
        else:
            destination.write_text(rendered)
