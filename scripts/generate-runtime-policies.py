#!/usr/bin/env python3
"""Generate shared product budgets; no platform policy or algorithms here."""
import argparse, json, re
from pathlib import Path
root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
spec = json.loads((root / 'resources/runtime-policies.json').read_text())
header = '// Generated by scripts/generate-runtime-policies.py.\n'
rust = header + ''.join(f'pub const {re.sub(r"([A-Z])", r"_\1", key).upper()}: u64 = {value};\n' for key, value in spec.items())
dart = header + 'abstract final class RuntimePolicy {\n' + ''.join(f'  static const {key} = {value};\n' for key, value in spec.items()) + '}\n'
swift = header + 'enum RuntimePolicy {\n' + ''.join(f'    static let {key} = {value}\n' for key, value in spec.items()) + '}\n'
for name, content in [('crates/anywhere-protocol/src/policy.rs', rust), ('apps/flutter/lib/infrastructure/runtime_policy.dart', dart), ('apps/flutter/macos/Runner/RuntimePolicy.swift', swift)]:
    p = root / name
    if args.check:
        assert p.read_text() == content, f'Outdated generated policy: {name}'
    else:
        p.write_text(content)
