#!/usr/bin/env python3
"""Generate shared HID keys, read-only legacy mappings and native adapter conversions."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
spec = json.loads((ROOT / 'resources/hotkey-keymap.json').read_text())
keys, modifiers = spec['keys'], spec['modifiers']
assert len({key['code'] for key in keys}) == len(keys), 'duplicate key code'
assert len({key['usage'] for key in keys}) == len(keys), 'duplicate portable key'
header = '// Generated by scripts/generate-keymap.py; edit resources/hotkey-keymap.json.\n'
dart = header + "import 'package:flutter/services.dart';\n\n"
for modifier in modifiers:
    dart += f"const shortcut{modifier['portableName'][0].upper() + modifier['portableName'][1:]} = {modifier['portableMask']};\n"
dart += 'const shortcutKeyNames = <int, String>{\n'
dart += ''.join(f"  {k['usage']}: '{k['name']}',\n" for k in keys) + '};\n'
for kind in ['Logical', 'Physical']:
    dart += f'final shortcut{kind}KeyCodes = <{kind}KeyboardKey, int>{{\n'
    dart += ''.join(f"  {kind}KeyboardKey.{k['logicalKey']}: {k['usage']},\n" for k in keys) + '};\n'
dart += 'const reservedActionKeyCodes = <int>{' + ', '.join(str(k['usage']) for k in keys if k['code'] in spec['reservedActionKeyCodes']) + '};\n'
legacy = header + "// Read-only migration for macOS settings versions 1–3. Never used for recording.\n"
legacy += 'const legacyMacKeyCodes = <int, int>{\n' + ''.join(f"  {k['code']}: {k['usage']},\n" for k in keys) + '};\n'
legacy += 'const legacyMacModifiers = <int, int>{\n' + ''.join(f"  {m['mask']}: {m['portableMask']},\n" for m in modifiers) + '};\n'
swift = header + 'enum NativeHotKeyMap {\n    static let keys: [UInt32: String] = [\n'
swift += ''.join(f'        {k["code"]}: "{k["name"]}",\n' for k in keys) + '    ]\n'
swift += '    static let modifiers: [(UInt32, String)] = [\n'
swift += ''.join(f'        ({m["mask"]}, "{m["label"]}"),\n' for m in modifiers) + '    ]\n'
swift += '    static let reservedActionKeyCodes: Set<UInt32> = [' + ', '.join(map(str, spec['reservedActionKeyCodes'])) + ']\n'
swift += '''    static func label(code: UInt32, modifiers mask: UInt32) -> String {
        modifiers.filter { mask & $0.0 != 0 }.map { $0.1 }.joined() + (keys[code] ?? "Key")
    }
}
'''
swift += 'extension NativeHotKeyMap {\n    static let portableKeys: [UInt32: UInt32] = [\n'
swift += ''.join(f"        {k['code']}: {k['usage']},\n" for k in keys) + '    ]\n'
swift += '    static let portableModifiers: [(UInt32, UInt32)] = [\n'
swift += ''.join(f"        ({m['mask']}, {m['portableMask']}),\n" for m in modifiers) + '    ]\n'
swift += """    static func nativeCode(_ usage: UInt32) -> UInt32? {
        portableKeys.first { $0.value == usage }?.key
    }
    static func nativeMask(_ mask: UInt32) -> UInt32? {
        guard mask & ~UInt32(15) == 0 else { return nil }
        return portableModifiers.reduce(0) { $0 | (mask & $1.1 != 0 ? $1.0 : 0) }
    }
    static func portableMask(_ mask: UInt32) -> UInt32 {
        portableModifiers.reduce(0) { $0 | (mask & $1.0 != 0 ? $1.1 : 0) }
    }
}
"""
outputs = {'apps/flutter/lib/infrastructure/hotkey_keymap.dart': dart,
           'apps/flutter/macos/Runner/HotKeyMap.swift': swift,
           'apps/flutter/lib/infrastructure/legacy_macos_shortcuts.dart': legacy}
for relative, content in outputs.items():
    path = ROOT / relative
    if args.check:
        assert path.exists() and path.read_text() == content, f'outdated key map: {relative}'
    else:
        path.write_text(content)
print('Hotkey key maps are consistent' if args.check else 'Generated hotkey key maps')
