#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn payloads_reject_ambiguous_sensitive_or_oversized_data() {
        let text = ClipboardPayload::text("hello 中文");
        text.validate().unwrap();
        let mut duplicate = text.clone();
        duplicate.formats.extend(text.formats);
        assert!(duplicate.validate().is_err());
        for name in [
            "org.nspasteboard.ConcealedType",
            "x-kde-passwordManagerHint",
        ] {
            assert!(ClipboardPayload {
                formats: vec![ClipboardFormat {
                    name: name.into(),
                    data: vec![]
                }]
            }
            .validate()
            .is_err());
        }
        assert!(ClipboardPayload::text(&"x".repeat(MAX_PAYLOAD_BYTES + 1))
            .validate()
            .is_err());
        assert!(ClipboardPayload {
            formats: vec![ClipboardFormat {
                name: FILES.into(),
                data: br#"["relative"]"#.to_vec()
            }]
        }
        .validate()
        .is_err());
    }
}
