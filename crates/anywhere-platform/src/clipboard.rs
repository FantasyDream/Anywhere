//! Serializable clipboard representations, independent of any UI or database.
use crate::ContextReadError;
use anyhow::{ensure, Result};

pub const TEXT: &str = "text/plain;charset=utf-8";
pub const FILES: &str = "application/x-anywhere-file-list+json";
pub const MAX_PAYLOAD_BYTES: usize = 16 * 1024 * 1024;
pub const MAX_FORMATS: usize = 64;
// Dynamic macOS UTIs encode application data flavors and can exceed 256 bytes.
pub const MAX_FORMAT_NAME_BYTES: usize = 4096;

fn valid_format_name(name: &str) -> bool {
    !name.is_empty() && name.len() <= MAX_FORMAT_NAME_BYTES && !name.contains('\0')
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ClipboardFormat {
    pub name: String,
    pub data: Vec<u8>,
}
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ClipboardPayload {
    pub formats: Vec<ClipboardFormat>,
}
impl ClipboardPayload {
    pub fn text(text: &str) -> Self {
        Self {
            formats: vec![ClipboardFormat {
                name: TEXT.into(),
                data: text.as_bytes().to_vec(),
            }],
        }
    }
    pub fn validate(&self) -> Result<()> {
        ensure!(
            !self.formats.is_empty() && self.formats.len() <= MAX_FORMATS,
            ContextReadError::TooManyItems
        );
        let mut names = std::collections::BTreeSet::new();
        let mut total = 0usize;
        for format in &self.formats {
            ensure!(valid_format_name(&format.name), "invalid clipboard format");
            ensure!(names.insert(&format.name), "duplicate clipboard format");
            ensure!(
                !sensitive_format(&format.name),
                "sensitive clipboard format"
            );
            total = total
                .checked_add(format.data.len())
                .ok_or(ContextReadError::TooLarge)?;
            ensure!(total <= MAX_PAYLOAD_BYTES, ContextReadError::TooLarge);
        }
        if let Some(text) = self.plain_text() {
            ensure!(!text.contains('\0'), "invalid clipboard text");
        }
        if self.formats.iter().any(|f| f.name == TEXT) {
            ensure!(self.plain_text().is_some(), "invalid clipboard UTF-8");
        }
        if self.formats.iter().any(|f| f.name == FILES) {
            self.files()?;
        }
        Ok(())
    }
    pub fn byte_count(&self) -> usize {
        self.formats.iter().map(|f| f.data.len()).sum()
    }
    pub fn plain_text(&self) -> Option<&str> {
        self.formats
            .iter()
            .find(|f| f.name == TEXT)
            .and_then(|f| std::str::from_utf8(&f.data).ok())
    }
    pub fn files(&self) -> Result<Vec<String>> {
        let Some(format) = self.formats.iter().find(|f| f.name == FILES) else {
            return Ok(vec![]);
        };
        let paths: Vec<String> = serde_json::from_slice(&format.data)?;
        ensure!(
            !paths.is_empty() && paths.len() <= 4096,
            ContextReadError::TooManyItems
        );
        ensure!(
            paths
                .iter()
                .all(|p| std::path::Path::new(p).is_absolute() && !p.contains('\0')),
            "invalid clipboard file path"
        );
        Ok(paths)
    }
}
pub fn sensitive_format(name: &str) -> bool {
    let name = name.to_ascii_lowercase();
    [
        "org.nspasteboard.transienttype",
        "org.nspasteboard.concealedtype",
        "org.nspasteboard.autogeneratedtype",
        "com.agilebits.onepassword",
        "x-kde-passwordmanagerhint",
        "excludecipboardcontentfrommonitorprocessing",
        "excludeclipboardcontentfrommonitorprocessing",
    ]
    .iter()
    .any(|n| name == *n)
}
