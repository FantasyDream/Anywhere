//! Shared by Cargo's build script and the checked-in catalogue generator.
use std::{fs, io, path::Path};

fn invalid(message: impl Into<String>) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidData, message.into())
}

/// Discover only module-owned registration.rs files. Business code and manifest
/// content are not interpreted; Rust type-checks the registration declarations.
pub fn discover(crate_root: &Path) -> io::Result<Vec<String>> {
    let root = crate_root.join("src/features");
    let mut sources = Vec::new();
    for entry in fs::read_dir(&root)? {
        let entry = entry?;
        let kind = entry.file_type()?;
        if kind.is_symlink() {
            return Err(invalid(
                "symlinks are not supported in the feature source directory",
            ));
        }
        if !kind.is_dir() {
            continue;
        }
        let registration = entry.path().join("registration.rs");
        let metadata = match fs::symlink_metadata(&registration) {
            Ok(metadata) => metadata,
            Err(error) if error.kind() == io::ErrorKind::NotFound => continue,
            Err(error) => return Err(error),
        };
        if !metadata.file_type().is_file() {
            return Err(invalid(
                "feature registration must be a regular source file",
            ));
        }
        let name = entry.file_name();
        let name = name
            .to_str()
            .ok_or_else(|| invalid("invalid feature directory name"))?;
        if name.is_empty()
            || !name.as_bytes()[0].is_ascii_lowercase()
            || !name
                .bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
        {
            return Err(invalid(format!("invalid feature source directory: {name}")));
        }
        sources.push(format!("src/features/{name}/registration.rs"));
    }
    sources.sort();
    if sources.is_empty() {
        return Err(invalid("no builtin feature registrations found"));
    }
    Ok(sources)
}

pub fn render(sources: &[String]) -> String {
    let mut output = String::from(
        "// Generated by cargo run -p anywhere-core --example generate_feature_catalog.\n\
         // Cargo also generates this catalogue in OUT_DIR; do not edit this snapshot.\n",
    );
    for (index, source) in sources.iter().enumerate() {
        output.push_str(&format!(
            "mod registration_{index} {{\n    include!(concat!(\n        env!(\"CARGO_MANIFEST_DIR\"),\n        \"/\",\n        {source:?}\n    ));\n}}\n"
        ));
    }
    output.push_str("const BUILTIN_FEATURE_GROUPS: &[&[BuiltinFeatureRegistration]] = &[\n");
    for index in 0..sources.len() {
        output.push_str(&format!("    registration_{index}::REGISTRATIONS,\n"));
    }
    output.push_str("];\n");
    output
}

pub fn write_or_check(path: &Path, content: &str, check: bool) -> io::Result<()> {
    let current = match fs::read_to_string(path) {
        Ok(current) => Some(current),
        Err(error) if error.kind() == io::ErrorKind::NotFound => None,
        Err(error) => return Err(error),
    };
    // Git can check text files out as CRLF on Windows. Checking a generated
    // snapshot must ignore that representation without rewriting the checkout.
    if current
        .as_deref()
        .is_some_and(|current| current.replace("\r\n", "\n") == content)
    {
        return Ok(());
    }
    if check {
        return Err(invalid(format!(
            "outdated feature catalogue: {}; run cargo run -p anywhere-core --example generate_feature_catalog",
            path.display()
        )));
    }
    fs::write(path, content)
}
